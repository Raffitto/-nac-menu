export function augustProductRows({ extraStaff = [] } = {}) {
  const rows = [];
  Object.entries(AUGUST_MATRIX).forEach(([item, byStaff]) => {
    Object.entries(byStaff).forEach(([staff, qty]) => {
      if (!qty) return;
      rows.push({
        waiter_name: staff,
        raw_item_name: item,
        quantity_sold: qty,
        gross_sales: qty * (UNIT_SALES[item] || 10),
      });
    });
  });
  extraStaff.forEach((row) => rows.push(row));
  return rows;
}
